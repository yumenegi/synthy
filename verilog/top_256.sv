module top_256(
    input  logic       Clk,
    input  logic [15:0] SW,
    input  logic [ 3:0] BTN,
    output logic [15:0] LED,
    input  logic        JA1_P,      // SPI_CS_N
    input  logic        JA1_N,      // SPI_MOSI
    output logic        JA2_P,      // SPI_MISO
    input  logic        JA2_N,      // SPI_SCK
    output logic        JB1_P,      // I2S_MCLK
    output logic        JB1_N,      // I2S_BCLK
    output logic        JB2_P,      // I2S_LRCLK
    output logic        JB2_N,      // I2S_SDATA
    output logic        SPKL,
    output logic        SPKR,
    output logic [2:0]  RGB0,
    output logic [2:0]  RGB1
    );
    
    // clk sig
    logic clk_sys;
    logic clk_audio;
    
    // Write strobe signal
    logic wr_strb;
    
    // clk locked
    logic locked;
    logic reset;

    assign reset = BTN[0];
    
    // instantiate clock wiz
    clk_wiz_0 clk_wiz (
        .reset(reset),
        .clk_in1(Clk),
        .clk(clk_sys),
        .clk_audio(clk_audio),
        .locked(locked)
    );
    
    // sync signal generation from i2s transmitter
    // literally just to generate the audio sync pulse
    // does nothing right now
    i2s_transmitter i2s_inst (
        .clk_audio(clk_audio),
        .reset(~locked),         // reset if clock unlocks
        // .sample_in(audio_out[0]), // data from Synth
//        .bclk(i2s_bclk),
//        .lrclk(i2s_lrclk),
//        .sdata(i2s_sdata),
        .ready_for_sample(wr_strb) // request signal
    );

    // engine wires
    logic [16:0] eng_addr_a, eng_addr_b;
    logic [15:0] eng_wdata;
    logic [3:0]  eng_we; // Write enables for the 4 banks
    
    // Data returning from BRAMs
    logic [15:0] b0_dout_a, b0_dout_b;
    logic [15:0] b1_dout_a, b1_dout_b;
    logic [15:0] b2_dout_a, b2_dout_b;
    logic [15:0] b3_dout_a, b3_dout_b;
    
    logic [15:0] audio_final;

    // testing params
    // 1 hz number of strides
    localparam logic [31:0] FREQ_TO_STRIDE_CONST = 32'd97392;
    logic [31:0] base_stride;

    // BANK 0
    wt_bram bank0 (
        .clka(clk_sys), .addra(eng_addr_a), .douta(b0_dout_a), .wea(1'b0), .dina(16'b0),
        .clkb(clk_sys), .addrb(eng_addr_b), .doutb(b0_dout_b),
        .web(eng_we[0]), .dinb(eng_wdata)
    );

    // BANK 1
    wt_bram_tri bank1 (
        .clka(clk_sys), .addra(eng_addr_a), .douta(b1_dout_a), .wea(1'b0), .dina(16'b0),
        .clkb(clk_sys), .addrb(eng_addr_b), .doutb(b1_dout_b), 
        .web(eng_we[1]), .dinb(eng_wdata) 
    );

    // BANK 2
    wt_bram_sq bank2 (
        .clka(clk_sys), .addra(eng_addr_a), .douta(b2_dout_a), .wea(1'b0), .dina(16'b0),
        .clkb(clk_sys), .addrb(eng_addr_b), .doutb(b2_dout_b), 
        .web(eng_we[2]), .dinb(eng_wdata) 
    );

    // BANK 3
    wt_bram bank3 (
        .clka(clk_sys), .addra(eng_addr_a), .douta(b3_dout_a), .wea(1'b0), .dina(16'b0),
        .clkb(clk_sys), .addrb(eng_addr_b), .doutb(b3_dout_b), 
        .web(eng_we[3]), .dinb(eng_wdata) 
    );

    logic [7:0]  param_wr_addr;
    logic [2:0]  param_wr_en;   // [2]=Env, [1]=LFO, [0]=Op
    
    // Op Parameters
    logic [31:0] param_stride;
    logic [9:0]  param_wt_id;
    logic [2:0]  param_wt_lfo_id;
    logic [2:0]  param_env_id;
    logic        param_key_on;
    
    // LFO Parameters
    logic [31:0] param_lfo_stride;
    
    // Envelope Parameters
    logic [7:0]  param_ar;
    logic [3:0]  param_ar_rs;
    logic [7:0]  param_dr;
    logic [3:0]  param_dr_rs;
    logic [15:0] param_sl;
    logic [7:0]  param_rr;
    logic [3:0]  param_rr_rs;

    // MCU Write Interface (Wavetable Loading)
    logic        mcu_wr_en;
    logic [1:0]  mcu_wr_bank;
    logic [16:0] mcu_wr_addr;
    logic [15:0] mcu_wr_data;

    // bottom switches is hz increase
    // top switches are octaves
    logic [31:0] stride_in;
    assign base_stride = SW[7:0] * FREQ_TO_STRIDE_CONST;    
    assign stride_in = base_stride << SW[10:8];

    board_test tester (
        .clk(clk_sys),
        .btn(BTN[1]),
        .stride_in(stride_in),
        .param_stride(param_stride),
        .param_wr_en(param_wr_en),
        .param_wr_addr(param_wr_addr),
        .param_wt_id(param_wt_id),
        .param_env_id(param_env_id),
        .param_wt_lfo_id(param_wt_lfo_id),
        .param_key_on(param_key_on),
        .param_ar(param_ar), 
        .param_ar_rs(param_ar_rs),
        .param_dr(param_dr),
        .param_dr_rs(param_dr_rs),
        .param_sl(param_sl),
        .param_rr(param_rr),
        .param_rr_rs(param_rr_rs)
    );

    synth_engine_256 engine (
        .clk(clk_sys),
        .reset(reset),
        .wr_strb(wr_strb),
        
        // --- Write Interface (Connected to SPI signals) ---
        .param_wr_addr(param_wr_addr),
        .param_wr_en(param_wr_en), // 3-bit vector
        
        // Op Params
        .param_key_on_in(param_key_on),
        .param_stride_in(param_stride),
        .param_wt_id_in(param_wt_id),
        .param_wt_lfo_id_in(param_wt_lfo_id),
        .param_env_id_in(param_env_id),
        
        // LFO Params
        .param_lfo_stride_in(param_lfo_stride),
        
        // Envelope Params
        .param_ar_in(param_ar), .param_ar_rs_in(param_ar_rs),
        .param_dr_in(param_dr), .param_dr_rs_in(param_dr_rs),
        .param_sl_in(param_sl),
        .param_rr_in(param_rr), .param_rr_rs_in(param_rr_rs),
        
        // MCU Wavetable Write
        .mcu_wr_en(mcu_wr_en), 
        .mcu_wr_bank(mcu_wr_bank), 
        .mcu_wr_addr(mcu_wr_addr), 
        .mcu_wr_data(mcu_wr_data),
        
        // BRAM Interface
        .bram_addr_a(eng_addr_a), .bram_addr_b(eng_addr_b),
        .bram_wdata(eng_wdata), .bram_we(eng_we),
        .bram0_data_a(b0_dout_a), .bram0_data_b(b0_dout_b),
        .bram1_data_a(b1_dout_a), .bram1_data_b(b1_dout_b),
        .bram2_data_a(b2_dout_a), .bram2_data_b(b2_dout_b),
        .bram3_data_a(b3_dout_a), .bram3_data_b(b3_dout_b),
        
        .audio_out(audio_final)
    );

    sigma_delta pdm (
        .clk(clk_sys),
        .reset(~locked),
        .pcm(audio_final),
        .pdm(SPKL)
    );
    assign SPKR = SPKL;
endmodule
